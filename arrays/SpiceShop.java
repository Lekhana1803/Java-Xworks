class SpiceShop {
    static String powderedSpices[] = {"Turmeric", "Cumin Powder", "Coriander Powder", "Red Chili Powder"};
    static String wholeSpices[] = {"Cloves", "Cardamom", "Cinnamon", "Black Pepper"};
    static String spiceBlends[] = {"Garam Masala", "Sambar Powder", "Chaat Masala"};
    static String seeds[] = {"Mustard Seeds", "Fenugreek Seeds", "Fennel Seeds"};
    static String herbs[] = {"Basil", "Oregano", "Thyme", "Bay Leaf"};
    static String driedLeaves[] = {"Curry Leaves", "Mint Leaves", "Kaffir Lime Leaves"};
    static String seasoningMixes[] = {"Tandoori Masala", "Pav Bhaji Masala", "Biryani Masala"};
    static String regionalSpices[] = {"Kashmiri Chili", "Malvani Masala", "Chettinad Masala"};

    public static void main(String[] args) {
        System.out.println("Powdered Spices: " + powderedSpices[0] + ", " + powderedSpices[1] + ", " + powderedSpices[2]);
        System.out.println("Length: " + powderedSpices.length);

        System.out.println("Whole Spices: " + wholeSpices[0] + ", " + wholeSpices[1] + ", " + wholeSpices[2]);
        System.out.println("Length: " + wholeSpices.length);

        System.out.println("Spice Blends: " + spiceBlends[0] + ", " + spiceBlends[1] + ", " + spiceBlends[2]);
        System.out.println("Length: " + spiceBlends.length);

        System.out.println("Seeds: " + seeds[0] + ", " + seeds[1] + ", " + seeds[2]);
        System.out.println("Length: " + seeds.length);

        System.out.println("Herbs: " + herbs[0] + ", " + herbs[1] + ", " + herbs[2]);
        System.out.println("Length: " + herbs.length);

        System.out.println("Dried Leaves: " + driedLeaves[0] + ", " + driedLeaves[1] + ", " + driedLeaves[2]);
        System.out.println("Length: " + driedLeaves.length);

        System.out.println("Seasoning Mixes: " + seasoningMixes[0] + ", " + seasoningMixes[1] + ", " + seasoningMixes[2]);
        System.out.println("Length: " + seasoningMixes.length);

        System.out.println("Regional Spices: " + regionalSpices[0] + ", " + regionalSpices[1] + ", " + regionalSpices[2]);
        System.out.println("Length: " + regionalSpices.length);
    }
}

